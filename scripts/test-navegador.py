import sys, json, urllib.parse
# Usa un catálogo fijo (scripts/fixtures/productos-web.json) para que las pruebas no dependan de las existencias del día.
from playwright.sync_api import sync_playwright
S=sys.argv[1]; URL='http://localhost:8765/'
res=[]; errs=[]
def ok(n,c,extra=''):
    res.append((n,bool(c))); print(('  ✓ ' if c else '  ✗ ')+n+(' '+str(extra) if not c and extra else ''))
D=json.load(open('scripts/fixtures/productos-web.json'))['productos']
NC=sum(1 for x in D if x['catalogo']=='caballeros'); ND=sum(1 for x in D if x['catalogo']=='damas')
CS=sum(1 for x in D if x['catalogo']=='caballeros' and x['estado']=='coming_soon'); AG=sum(1 for x in D if x['catalogo']=='caballeros' and x['estado']=='agotado')
NODISP=sum(1 for x in D if x['catalogo']=='caballeros' and not (x['estado']=='disponible' and x.get('existencias')!=0))
with sync_playwright() as p:
    b=p.chromium.launch()
    ctx=b.new_context(viewport={'width':390,'height':844}, device_scale_factor=2, is_mobile=True, has_touch=True); ctx.route('**/data/productos.json', lambda r: r.fulfill(path='scripts/fixtures/productos-web.json', content_type='application/json'))
    pg=ctx.new_page(); pg.on('console', lambda m: m.type=='error' and errs.append(m.text)); pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto(URL); pg.wait_for_selector('.tarjeta')
    pg.screenshot(path=f'{S}/shots/m1-inicio.png')
    ok(f'Caballeros muestra {NC}', pg.locator('.tarjeta').count()==NC)
    ok('Coming soon y Agotado visibles', pg.locator('.estado.coming').count()==CS and pg.locator('.estado.agotado').count()==AG)
    ok('Botones de no disponibles desactivados', pg.locator('.tarjeta.no-disp .btn-agregar:disabled').count()==NODISP)
    pg.click('#tab-damas'); pg.wait_for_timeout(300)
    ok(f'Damas muestra {ND}', pg.locator('.tarjeta').count()==ND)
    pg.click('#tab-caballeros')
    pg.fill('#q','hawas'); pg.wait_for_timeout(300)
    ok('Búsqueda "hawas" → 3', pg.locator('.tarjeta').count()==3)
    pg.fill('#q','latafa'); pg.wait_for_timeout(300)
    ok('Búsqueda con error "latafa" encuentra Lattafa', pg.locator('.tarjeta').count()>=3, pg.locator('.tarjeta').count())
    pg.fill('#q','yara'); pg.wait_for_timeout(300)
    ok('Aviso de resultados en Damas', pg.locator('.otra-cat:not([hidden])').count()==1)
    pg.screenshot(path=f'{S}/shots/m2-busqueda-otra.png')
    pg.click('.limpiar-q'); pg.wait_for_timeout(200)
    # filtros
    pg.click('.btn-filtros'); pg.wait_for_timeout(450)
    pg.screenshot(path=f'{S}/shots/m3-filtros.png')
    pg.click('label.opcion:has(input[name=estado][value=disponible])')
    pg.click('label.opcion:has(input[name=marca][value=Rasasi])')
    pg.click('[data-accion=aplicar-filtros]'); pg.wait_for_timeout(450)
    NR=sum(1 for x in D if x['catalogo']=='caballeros' and x['marca']=='Rasasi' and x['estado']=='disponible')
    ok(f'Filtro Disponibles + Rasasi → {NR}', pg.locator('.tarjeta').count()==NR, pg.locator('.tarjeta').count())
    pg.click('[data-accion=quitar-filtro][data-tipo=marca]'); pg.click('[data-accion=quitar-filtro][data-tipo=estado]'); pg.wait_for_timeout(200)
    ok(f'Quitar filtros → {NC}', pg.locator('.tarjeta').count()==NC)
    # carrito
    def add(id): pg.click(f'.tarjeta[data-id="{id}"] [data-accion=agregar]')
    def mas(id): pg.click(f'.tarjeta[data-id="{id}"] [data-accion=mas]')
    add('H03'); pg.wait_for_timeout(100)
    ok('1 unidad: barra dice faltan 5', 'Faltan 5' in pg.inner_text('.bp-linea2'), pg.inner_text('.bp-linea2'))
    ok('Total C$1,490', pg.inner_text('.bp-total')=='C$1,490')
    mas('H03'); mas('H03'); add('H15'); add('H10')
    ok('5 unidades: faltan 1', 'Faltan 1' in pg.inner_text('.bp-linea2'))
    pg.screenshot(path=f'{S}/shots/m4-cinco.png')
    mas('H10')
    pg.wait_for_timeout(300)
    ok('6 unidades: mayoreo activado', 'mayorista' in pg.inner_text('.bp-linea1') and pg.locator('.barra-pedido.mayor').count()==1)
    PM={x['id']:x['precios']['mayor'] for x in D}
    exp=3*PM['H03']['cs']+PM['H15']['cs']+2*PM['H10']['cs']
    expu=(3*round(PM['H03']['usd']*100)+round(PM['H15']['usd']*100)+2*round(PM['H10']['usd']*100))/100
    ok(f'Total mayorista C${exp:,}', pg.inner_text('.bp-total')==f'C${exp:,}', pg.inner_text('.bp-total'))
    pg.click('.bp-boton'); pg.wait_for_timeout(500)
    pg.screenshot(path=f'{S}/shots/m5-pedido-mayor.png')
    ok('Hoja: 3 líneas', pg.locator('.linea').count()==3)
    ok('Hoja: total C$ y US$', pg.inner_text('.t-cs')==f'C${exp:,}' and pg.inner_text('.t-usd')==f'${expu:,.2f}', (pg.inner_text('.t-cs'),pg.inner_text('.t-usd')))
    href=pg.get_attribute('.btn-enviar','href'); msg=urllib.parse.unquote(href.split('text=')[1])
    ok('Enlace WhatsApp correcto', href.startswith('https://wa.me/50584735485?text=') and 'MAYORISTA' in msg and 'Total de unidades: 6' in msg)
    print('----- mensaje -----\n'+msg+'\n-------------------')
    pg.click('.linea:has-text("Hawas Ice") [data-accion=menos]'); pg.wait_for_timeout(300)
    ok('Baja a 5: vuelve a detalle', pg.inner_text('.t-nivel')=='Al detalle' and pg.inner_text('.t-cs')==f'C${3*1490+1490+1930:,}', pg.inner_text('.t-cs'))
    pg.click('.linea:has-text("Asad") [data-accion=quitar]'); pg.wait_for_timeout(200)
    ok('Eliminar línea', pg.locator('.linea').count()==2)
    pg.screenshot(path=f'{S}/shots/m6-pedido-detalle.png')
    pg.keyboard.press('Escape'); pg.wait_for_timeout(400)
    ok('Cerrar con Escape', not pg.locator('#hoja-pedido[open]').count())
    # persistencia
    pg.reload(); pg.wait_for_selector('.tarjeta')
    ok('Pedido se conserva al recargar', pg.inner_text('.bp-total')==f'C${3*1490+1930:,}', pg.inner_text('.bp-total'))
    # ficha
    pg.click('.tarjeta[data-id="H04"] .t-abrir'); pg.wait_for_timeout(450)
    pg.screenshot(path=f'{S}/shots/m7-ficha.png')
    ok('Ficha muestra 120 ml y precios', '120 ml' in pg.inner_text('#hoja-ficha') and 'C$1,845' in pg.inner_text('#hoja-ficha'))
    pg.click('[data-accion=ficha-mas]'); pg.click('[data-accion=ficha-agregar]'); pg.wait_for_timeout(450)
    ok('Ficha agrega 2 → 6 unidades → mayoreo', pg.locator('.barra-pedido.mayor').count()==1)
    pg.click('.tarjeta[data-id="H02"] .t-abrir'); pg.wait_for_timeout(450)
    ok('Ficha de coming soon no permite agregar', pg.locator('#hoja-ficha [data-accion=ficha-agregar]').count()==0)
    pg.screenshot(path=f'{S}/shots/m8-ficha-coming.png')
    pg.keyboard.press('Escape'); pg.wait_for_timeout(350)
    pg.evaluate('window.scrollTo(0, document.body.scrollHeight)'); pg.wait_for_timeout(300)
    pg.screenshot(path=f'{S}/shots/m9-condiciones.png')
    ok('Condiciones: CargoTrans, 2 a 4 días, 6 unidades', all(s in pg.inner_text('#condiciones') for s in ['CargoTrans','2 a 4 días','6 unidades']))
    ov=pg.evaluate('document.documentElement.scrollWidth > window.innerWidth')
    ok('Sin desbordamiento horizontal en 390px', not ov)
    pg.evaluate('window.scrollTo(0,0)'); pg.wait_for_timeout(200)
    pg.screenshot(path=f'{S}/shots/m0-full.png', full_page=True)
    # pantalla pequeña 320
    pg.set_viewport_size({'width':320,'height':640}); pg.wait_for_timeout(300)
    ok('Sin desbordamiento en 320px', not pg.evaluate('document.documentElement.scrollWidth > window.innerWidth'))
    pg.screenshot(path=f'{S}/shots/m10-320.png')
    # escritorio
    d=b.new_page(viewport={'width':1440,'height':900}); d.on('pageerror', lambda e: errs.append(str(e)))
    d.goto(URL); d.wait_for_selector('.tarjeta'); d.wait_for_timeout(300)
    d.screenshot(path=f'{S}/shots/d1-escritorio.png')
    d.click('.bp-boton'); d.wait_for_timeout(500); d.screenshot(path=f'{S}/shots/d2-pedido.png')
    ok('Sin errores de JavaScript', not errs, errs)
    b.close()
print(f"\n{sum(1 for _,c in res if c)} de {len(res)} pruebas en navegador correctas")
